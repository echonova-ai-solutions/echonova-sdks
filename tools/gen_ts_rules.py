#!/usr/bin/env python3
"""Generate the TypeScript SDK's copy of the shared error rules.

    python3 tools/gen_ts_rules.py           # write js/src/core/rules.generated.ts
    python3 tools/gen_ts_rules.py --check   # exit 1 if the file is stale (CI)

The rules are compiled into a TypeScript module rather than imported as JSON,
so the package behaves the same in every bundler and runtime (no JSON import
attributes needed). Only what the SDK uses at runtime is kept: comments,
descriptions and test vectors are left out. The tests read the vectors from
spec/ directly.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "spec" / "error-rules.json"
TARGET = ROOT / "js" / "src" / "core" / "rules.generated.ts"

# Only what the runtime uses; documentation-only keys added to the spec later never reach the bundle.
RUNTIME_KEYS = ("version", "taxonomy", "transport", "rules", "defaults")
DROPPED_TRANSPORT = ("description",)


def runtime_data(data: dict[str, Any]) -> dict[str, Any]:
    kept = {key: data[key] for key in RUNTIME_KEYS}
    kept["transport"] = [
        {key: value for key, value in row.items() if key not in DROPPED_TRANSPORT} for row in data["transport"]
    ]
    return kept


def render(source_bytes: bytes) -> str:
    data = json.loads(source_bytes)
    digest = hashlib.sha256(source_bytes).hexdigest()
    body = json.dumps(runtime_data(data), indent=2, ensure_ascii=False)
    return (
        "// Generated by tools/gen_ts_rules.py from spec/error-rules.json. Do not edit by hand.\n"
        f"// Source sha256: {digest}\n"
        "// Regenerate: python3 tools/gen_ts_rules.py\n"
        "\n"
        "import type { RulesData } from './rules.js';\n"
        "\n"
        f"export const RULES_DATA: RulesData = {body};\n"
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="exit 1 if the generated file is stale")
    args = parser.parse_args()

    expected = render(SOURCE.read_bytes())
    current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else None
    if current == expected:
        return 0
    relative = TARGET.relative_to(ROOT)
    if args.check:
        print(f"stale: {relative} (run python3 tools/gen_ts_rules.py)")
        return 1
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(expected, encoding="utf-8", newline="\n")
    print(f"wrote {relative}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
